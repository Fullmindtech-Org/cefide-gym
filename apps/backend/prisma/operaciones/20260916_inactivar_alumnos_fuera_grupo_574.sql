SELECT count(*) AS dni_a_conservar FROM alumnos_a_conservar;

-- Vista previa del alcance de la operacion.
WITH objetivos AS (
  SELECT a.id
  FROM public."Alumno" a
  WHERE a.activo = true
    AND NOT EXISTS (SELECT 1 FROM alumnos_a_conservar k WHERE k.dni = a.dni)
)
SELECT
  (SELECT count(*) FROM objetivos) AS alumnos_a_inactivar,
  (SELECT count(*) FROM public."InscripcionActividad" i JOIN objetivos o ON o.id = i."alumnoId") AS inscripciones_historicas_que_se_conservan;

UPDATE public."Alumno" a
SET activo = false
WHERE a.activo = true
  AND NOT EXISTS (
    SELECT 1
    FROM alumnos_a_conservar k
    WHERE k.dni = a.dni
  );

-- Resultado para auditoria: pagos, ingresos e inscripciones no se eliminan.
SELECT
  count(*) FILTER (WHERE activo) AS alumnos_activos,
  count(*) FILTER (WHERE NOT activo) AS alumnos_inactivos,
  (SELECT count(*) FROM public."InscripcionActividad") AS inscripciones_totales,
  (SELECT count(*) FROM public."Pago") AS pagos_historicos,
  (SELECT count(*) FROM public."Ingreso") AS ingresos_historicos
FROM public."Alumno";

